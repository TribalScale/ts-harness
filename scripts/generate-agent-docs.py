#!/usr/bin/env python3
"""Generate AGENTS/RULES identity sections from runtime YAML + catalog overlay.

Mechanical SoT: config/ts-harness-runtime.yaml.tmpl
Prose SoT: config/agents/catalog.yaml
Durable graphs: config/workflows/*.json

render-workspace.py remains responsible only for organization placeholders.
Run this script before render-workspace (or in CI --check mode).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
RUNTIME_TMPL = REPO_ROOT / "config" / "ts-harness-runtime.yaml.tmpl"
CATALOG_PATH = REPO_ROOT / "config" / "agents" / "catalog.yaml"
WORKFLOWS_DIR = REPO_ROOT / "config" / "workflows"
WORKSPACE = REPO_ROOT / "workspace"
SKILLS_DIR = REPO_ROOT / "skills"

BEGIN = "<!-- BEGIN GENERATED: agent-identity -->"
END = "<!-- END GENERATED: agent-identity -->"
HEADER = (
    "<!-- GENERATED by scripts/generate-agent-docs.py — do not hand-edit this block. "
    "Source: config/ts-harness-runtime.yaml.tmpl + config/agents/catalog.yaml -->"
)


def _load_yaml(path: Path) -> dict[str, Any]:
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict):
        raise SystemExit(f"{path}: expected mapping")
    return data


def load_runtime_agents() -> list[dict[str, Any]]:
    runtime = _load_yaml(RUNTIME_TMPL)
    agents = ((runtime.get("agents") or {}).get("list")) or []
    if not isinstance(agents, list) or not agents:
        raise SystemExit("runtime agents.list is empty")
    seen: set[str] = set()
    for agent in agents:
        agent_id = str(agent.get("id") or "").strip()
        if not agent_id:
            raise SystemExit("agent missing id")
        if agent_id in seen:
            raise SystemExit(f"duplicate agent id: {agent_id}")
        seen.add(agent_id)
    return sorted(agents, key=lambda a: str(a.get("id") or ""))


def load_catalog() -> dict[str, Any]:
    catalog = _load_yaml(CATALOG_PATH)
    agents = catalog.get("agents") or {}
    if not isinstance(agents, dict):
        raise SystemExit("catalog.agents must be a mapping")
    return agents


def workflow_index() -> list[str]:
    names: list[str] = []
    for path in sorted(WORKFLOWS_DIR.glob("*.json")):
        if path.name == "schema.json":
            continue
        try:
            data = json.loads(path.read_text())
        except json.JSONDecodeError:
            continue
        if data.get("deprecated"):
            continue
        names.append(str(data.get("workflow_type") or path.stem))
    return names


def skill_dirs_exist(skill_names: list[str]) -> list[str]:
    missing: list[str] = []
    for name in skill_names:
        # Skills may be top-level dirs or nested groups; accept either.
        candidates = [
            SKILLS_DIR / name,
            SKILLS_DIR / name.replace("_", "-"),
        ]
        if not any(c.exists() for c in candidates) and not list(SKILLS_DIR.glob(f"**/{name}")):
            # Many configs use short names that map to directories (dev, qa, pm).
            if not (SKILLS_DIR / name.split("/")[0]).exists():
                missing.append(name)
    return missing


def _bullets(items: list[str] | None) -> str:
    if not items:
        return "- _(none)_"
    return "\n".join(f"- {item}" for item in items)


def _tools_block(agent: dict[str, Any]) -> str:
    tools = agent.get("tools") or {}
    allow = tools.get("allow") or []
    deny = tools.get("deny") or []
    toolsets = agent.get("toolsets") or []
    skills = agent.get("skills") or []
    lines = [
        f"**Model:** `{agent.get('model') or 'n/a'}`",
        f"**Workspace:** `{agent.get('workspace') or 'n/a'}`",
        f"**Toolsets:** {', '.join(f'`{t}`' for t in toolsets) or '_(none)_'}",
        f"**Skills:** {', '.join(f'`{s}`' for s in skills) or '_(none)_'}",
        "",
        "**tools.allow** (from `config/ts-harness-runtime.yaml`):",
        _bullets([str(x) for x in allow]),
        "",
        "**tools.deny** (from `config/ts-harness-runtime.yaml`):",
        _bullets([str(x) for x in deny]),
    ]
    return "\n".join(lines)


def render_agent_identity(agent: dict[str, Any], catalog_entry: dict[str, Any]) -> str:
    agent_id = str(agent["id"])
    title = str(catalog_entry.get("title") or agent_id)
    soul = str(catalog_entry.get("soul") or "").strip()
    trust = str(catalog_entry.get("trust_level") or "unspecified")
    capabilities = catalog_entry.get("capabilities") or []
    routing = catalog_entry.get("routing_signals") or []
    allowed = catalog_entry.get("allowed") or []
    not_allowed = catalog_entry.get("not_allowed") or []
    approvals = catalog_entry.get("approvals") or []
    notes = str(catalog_entry.get("notes") or "").strip()

    parts = [
        BEGIN,
        HEADER,
        f"# {agent_id} — {title}",
        "",
        f"**Soul:** {soul}" if soul else "**Soul:** _(see catalog)_",
        "",
        f"**Trust level:** `{trust}`",
        "",
        "**Routing signals:**",
        _bullets([str(x) for x in routing]),
        "",
        "**Capabilities:**",
        _bullets([str(x) for x in capabilities]),
        "",
        _tools_block(agent),
        "",
        "| Allowed | Not Allowed |",
        "| --- | --- |",
    ]
    rows = max(len(allowed), len(not_allowed), 1)
    for i in range(rows):
        left = allowed[i] if i < len(allowed) else ""
        right = not_allowed[i] if i < len(not_allowed) else ""
        parts.append(f"| {left} | {right} |")
    parts.extend(
        [
            "",
            "**Requires human approval for:**",
            _bullets([str(x) for x in approvals]),
        ]
    )
    if notes:
        parts.extend(["", f"**Notes:** {notes}"])
    parts.extend(
        [
            "",
            "Durable delivery graphs are defined in `config/workflows/*.json` "
            "(not restated here). Runtime tools/skills are owned by "
            "`config/ts-harness-runtime.yaml`.",
            END,
        ]
    )
    return "\n".join(parts) + "\n"


def render_root_index(agents: list[dict[str, Any]], catalog: dict[str, Any]) -> str:
    workflows = workflow_index()
    rows = []
    for agent in agents:
        agent_id = str(agent["id"])
        if agent_id == "orchestrator":
            continue
        entry = catalog.get(agent_id) or {}
        signals = "; ".join(str(x) for x in (entry.get("routing_signals") or [])[:3]) or "—"
        rows.append(f"| `{agent_id}` | {entry.get('title') or agent_id} | {signals} |")
    body = "\n".join(
        [
            BEGIN,
            HEADER,
            "# Agent Architecture — Orchestrator + Specialists",
            "",
            "This index is generated from `config/ts-harness-runtime.yaml.tmpl` "
            "and `config/agents/catalog.yaml`.",
            "",
            "## Routing table",
            "",
            "| Agent | Title | Routing signals |",
            "| --- | --- | --- |",
            *rows,
            "",
            "## Durable workflows",
            "",
            "Stage sequences live in workflow skeletons (do not duplicate here):",
            "",
            *[f"- `{name}` → `config/workflows/{name}.json`" for name in workflows],
            "",
            "## Context brokering",
            "",
            "- Pass only relevant memories and **continuity refs** to specialists.",
            "- Prefer artifact/snapshot IDs over pasted chat excerpts.",
            "- After completion, store learnings in memory for future use.",
            "",
            "## Interaction rules",
            "",
            "1. Specialists never talk to each other or the user directly — only via the orchestrator.",
            "2. Specialists return structured output to the orchestrator.",
            "3. Uncertain results (confidence < 0.7) must be declared.",
            END,
        ]
    )
    return body + "\n"


def render_rules_trust_block() -> str:
    return "\n".join(
        [
            BEGIN,
            HEADER,
            "## Trust Derivation",
            "",
            "Actions taken by any specialist agent are classified using four axes. "
            "The classification determines what is enforced at the config layer "
            "(`tools.allow` / `tools.deny` in `config/ts-harness-runtime.yaml`) "
            "and what requires human approval.",
            "",
            "Operators extending the classification table must update "
            "`config/ts-harness-runtime.yaml` and the specialist catalog entry "
            "in `config/agents/catalog.yaml`, then regenerate docs with "
            "`scripts/generate-agent-docs.py`.",
            END,
            "",
        ]
    )


def upsert_generated_block(path: Path, generated: str, *, default_suffix: str = "") -> str:
    text = path.read_text() if path.exists() else ""
    if BEGIN in text and END in text:
        pattern = re.compile(
            re.escape(BEGIN) + r".*?" + re.escape(END),
            re.DOTALL,
        )
        new_text = pattern.sub(generated.strip(), text, count=1)
        if not new_text.endswith("\n"):
            new_text += "\n"
        return new_text
    # Insert generated block at top; keep remainder as hand-maintained.
    remainder = text.lstrip("\n")
    combined = generated.rstrip() + "\n\n" + remainder
    if default_suffix and BEGIN not in text and not remainder:
        combined = generated.rstrip() + "\n\n" + default_suffix
        if not combined.endswith("\n"):
            combined += "\n"
        return combined
    if not combined.endswith("\n"):
        combined += "\n"
    return combined


def patch_rules_file(path: Path) -> str:
    text = path.read_text() if path.exists() else ""
    # Replace or insert generated trust block.
    if "## Trust Derivation" in text and BEGIN not in text:
        # Replace from Trust Derivation through the next ## Scope or end of trust section
        trust_block = render_rules_trust_block().rstrip()
        pattern = re.compile(
            r"## Trust Derivation\n.*?(?=\n## Scope Limits|\n## |\\Z)",
            re.DOTALL,
        )
        if pattern.search(text):
            text = pattern.sub(trust_block + "\n\n", text, count=1)
        else:
            text = upsert_generated_block(path, trust_block)
            return text
        return text if text.endswith("\n") else text + "\n"
    return upsert_generated_block(path, render_rules_trust_block().rstrip() + "\n", default_suffix=text)


def validate_catalog_coverage(agents: list[dict[str, Any]], catalog: dict[str, Any]) -> None:
    missing = [str(a["id"]) for a in agents if str(a["id"]) not in catalog]
    if missing:
        raise SystemExit(f"catalog missing agents: {', '.join(missing)}")


def validate_skills(agents: list[dict[str, Any]]) -> None:
    missing_all: list[str] = []
    for agent in agents:
        skills = [str(s) for s in (agent.get("skills") or [])]
        missing = skill_dirs_exist(skills)
        for name in missing:
            missing_all.append(f"{agent['id']}:{name}")
    if missing_all:
        # Soft for known short aliases that map to directories — only fail hard unknowns.
        hard = [m for m in missing_all if m.split(":", 1)[1] not in {
            "memory", "memory-api", "workflow", "workflows", "governed-workflows",
            "cost-awareness", "audit-logging", "dev", "ops", "qa", "pm", "comms",
            "integrate", "orchestrator",
        }]
        # Directory existence check for short names:
        for item in list(hard):
            agent_id, skill = item.split(":", 1)
            if (SKILLS_DIR / skill).exists():
                hard.remove(item)
        if hard:
            raise SystemExit(f"missing skill paths: {', '.join(hard)}")


def generate_all() -> dict[str, str]:
    agents = load_runtime_agents()
    catalog = load_catalog()
    validate_catalog_coverage(agents, catalog)
    validate_skills(agents)

    outputs: dict[str, str] = {}
    outputs[str(WORKSPACE / "AGENTS.md")] = render_root_index(agents, catalog)

    for agent in agents:
        agent_id = str(agent["id"])
        entry = catalog[agent_id]
        agent_dir = WORKSPACE / agent_id
        agent_dir.mkdir(parents=True, exist_ok=True)
        agents_path = agent_dir / "AGENTS.md"
        rules_path = agent_dir / "RULES.md"
        identity = render_agent_identity(agent, entry)
        outputs[str(agents_path)] = upsert_generated_block(agents_path, identity)
        outputs[str(rules_path)] = patch_rules_file(rules_path)

    return outputs


def write_outputs(outputs: dict[str, str]) -> None:
    for path_str, content in outputs.items():
        path = Path(path_str)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def check_outputs(outputs: dict[str, str]) -> None:
    diffs: list[str] = []
    for path_str, content in outputs.items():
        path = Path(path_str)
        current = path.read_text() if path.exists() else ""
        if current != content:
            diffs.append(str(path.relative_to(REPO_ROOT)))
    if diffs:
        raise SystemExit("generated docs drift:\n  - " + "\n  - ".join(diffs))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated docs would change",
    )
    args = parser.parse_args(argv)

    outputs = generate_all()
    if args.check:
        check_outputs(outputs)
        print("generate-agent-docs: OK")
        return 0

    write_outputs(outputs)
    print(f"generate-agent-docs: wrote {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
